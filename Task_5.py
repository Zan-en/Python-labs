a = int(input("Введите число а: "))
b = int(input("Введите число b: "))

print( f"Сумма а и b: {a+b};"
       f" Разность а и b: {a-b};"                      
       f" Произведение а и b: {a*b};"                                                        
       f" а в степени b: {a**b};")

if b != 0:
   print( f" Частное а и b: {a/b};"                     
          f" Остаток от деления а и b: {a%b};")
else:
   print(f"b={b}, поэтому поделить невозможно и получить остаток от деления тоже")